"""Run every EDA figure, then write reports/eda_summary.md and the EDA notebooks."""
from __future__ import annotations

import json
import logging
from pathlib import Path

import pandas as pd

from solvia.config import get_path, load_config, project_path
from solvia.eda import consumption, india, india_households, irradiance, solar
from solvia.viz import apply_style

log = logging.getLogger(__name__)

SECTIONS = {
    "india": ("India: solar resource, rainfall and estimated plant location (NASA POWER 2001–2025)", "03_eda_india"),
    "india_households": ("Indian households (Prayas eMARC smart meters, Maharashtra + Uttar Pradesh, 2018–2020)", "05_eda_india_households"),
    "solar": ("Solar plants (Kaggle, India)", "04_eda_solar_plants"),
    "consumption": ("Household consumption (UCI, France)", "02_eda_consumption"),
}


def run_eda() -> dict[str, list[dict]]:
    apply_style()
    interim, out = get_path("interim"), get_path("figures")
    daily = pd.read_parquet(interim / "household_daily.parquet").join(
        pd.read_parquet(interim / "household_weather_daily.parquet"), how="left")
    df15 = pd.concat([pd.read_parquet(interim / f"solar_plant{p}_15min.parquet") for p in (1, 2)], ignore_index=True)
    daily_inv = pd.read_parquet(interim / "solar_daily_inverter.parquet")
    daily_plant = pd.read_parquet(interim / "solar_daily_plant.parquet")
    cfg = load_config()
    threshold = cfg["monitoring"]["ratio_threshold"]
    ec = cfg["emarc"]
    mains = pd.read_parquet(interim / "emarc_mains_daily.parquet")
    india_daily = pd.read_parquet(interim / "india_weather_daily.parquet")
    clim = pd.read_parquet(interim / "india_monthly_climatology.parquet")
    climate = pd.read_parquet(interim / "india_location_climate.parquet")
    districts = pd.read_parquet(interim / "niti_districts_dec2024.parquet")

    results = {
        "solar": [f(df15, out) for f in solar.ALL_15MIN]
        + [f(daily_plant, out) for f in solar.ALL_DAILY_PLANT]
        + [solar.inverter_comparison(daily_inv, out), solar.inverter_heatmap(daily_inv, out),
           solar.peer_ratio_distribution(daily_inv, out, threshold)],
        "india": [
            india.city_ranking(climate, out),
            india.monthly_heatmap(clim, climate, out),
            india.climate_lines(clim, out),
            india.rain_and_dry_months(climate, out),
            india.nasa_vs_niti(india_daily, districts, pd.read_parquet(interim / "niti_kheda_monthly.parquet"), out),
            india.plant_location_match(pd.read_parquet(interim / "plant_location_match.parquet"), climate, out),
            india.plant_grid_map(pd.read_parquet(interim / "plant_grid_match.parquet"), out),
            irradiance.district_ranking(districts, out),
        ],
        "india_households": [
            india_households.households_overview(mains, out),
            india_households.consumption_by_type(mains, out),
            india_households.seasonal_by_region(mains, india_daily, ec["region_weather"], out),
            india_households.temperature_response(mains, india_daily, ec["region_weather"], out),
            india_households.load_profile(pd.read_parquet(interim / "emarc_load_profiles.parquet"), tuple(ec["solar_hours"]), out),
            india_households.lockdown_effect(mains, ec["lockdown_start"], out),
        ],
        "consumption": [f(daily, out) for f in consumption.ALL],
    }
    write_summary(results)
    write_notebooks(results)
    return results


def write_summary(results: dict[str, list[dict]]) -> None:
    project_path("reports/audit/eda_stats.json").write_text(json.dumps(results, indent=2, default=str), encoding="utf-8")
    lines = ["# EDA summary (Phase 2)", "",
             "*Generated by `python -m solvia.pipeline --steps eda`. Every number below is computed by the code.*", ""]
    for key in SECTIONS:                      # India first, then French household
        items = results[key]
        lines += [f"## {SECTIONS[key][0]}", ""]
        for r in items:
            lines += [f"### {r['title']}", "", f"![{r['title']}](figures/{r['file']})", "", f"**Takeaway:** {r['takeaway']}", ""]
    project_path("reports/eda_summary.md").write_text("\n".join(lines), encoding="utf-8")


def _notebook(title: str, intro: str, items: list[dict], code: str) -> dict:
    def md(text: str) -> dict:
        return {"cell_type": "markdown", "metadata": {}, "source": text.splitlines(keepends=True)}
    cells = [md(f"# {title}\n\n{intro}"),
             {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
              "source": code.splitlines(keepends=True)}]
    for r in items:
        cells.append(md(f"## {r['title']}\n\n![{r['title']}](../reports/figures/{r['file']})\n\n**Takeaway:** {r['takeaway']}"))
    return {"cells": cells, "metadata": {"kernelspec": {"display_name": "Python 3 (.venv)", "language": "python", "name": "python3"},
                                         "language_info": {"name": "python"}}, "nbformat": 4, "nbformat_minor": 5}


def write_notebooks(results: dict[str, list[dict]]) -> None:
    nb_dir = project_path("notebooks")
    code = ("# Regenerates every figure below from data/interim/ (reusable code lives in src/solvia/eda/).\n"
            "from solvia.eda.report import run_eda\n"
            "results = run_eda()\n")
    notebooks = {
        "02_eda_consumption": ("EDA: household consumption", "Daily consumption of one household in Sceaux, France (UCI, 2006–2010).",
                               results["consumption"]),
        "03_eda_india": ("EDA: India solar resource and rainfall",
                         "Daily NASA POWER weather for 50 Indian cities (2001–2025), validation against NITI Aayog, and an estimate of where the Kaggle plants are.",
                         results["india"]),
        "05_eda_india_households": ("EDA: Indian households (eMARC)",
                                    "Daily and 15-minute electricity use of Indian homes in Maharashtra and Uttar Pradesh "
                                    "(Prayas Energy Group eMARC smart meters, 2018–2020). Each meter is analysed separately.",
                                    results["india_households"]),
        "04_eda_solar_plants": ("EDA: Indian solar plants",
                                "Two Indian solar plants (Kaggle, 34 days, 22 inverters each).", results["solar"]),
    }
    for name, (title, intro, items) in notebooks.items():
        (nb_dir / f"{name}.ipynb").write_text(json.dumps(_notebook(title, intro, items, code), indent=1), encoding="utf-8")
        log.info("notebook written: %s.ipynb", name)
