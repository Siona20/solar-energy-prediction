"""Record what each cleaning step removed, changed or flagged, and write it as a report."""
from __future__ import annotations

import json
import logging
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

log = logging.getLogger(__name__)


@dataclass
class Step:
    dataset: str
    step: str
    rows_before: int
    rows_after: int
    affected: int = 0          # rows changed or flagged (not removed)
    note: str = ""

    @property
    def removed(self) -> int:
        return self.rows_before - self.rows_after


@dataclass
class CleaningLog:
    steps: list[Step] = field(default_factory=list)
    facts: dict[str, Any] = field(default_factory=dict)

    def add(self, dataset: str, step: str, before: int, after: int, affected: int = 0, note: str = "") -> None:
        s = Step(dataset, step, int(before), int(after), int(affected), note)
        self.steps.append(s)
        log.info("[%s] %s: %d -> %d rows (removed %d, affected %d) %s",
                 dataset, step, before, after, s.removed, affected, note)

    def fact(self, key: str, value: Any) -> None:
        """Store a named result (e.g. a cross-check statistic) for the report."""
        self.facts[key] = value

    def write(self, json_path: Path, md_path: Path, title: str = "Cleaning report (Phase 1)",
              command: str = "python -m solvia.pipeline --steps clean") -> None:
        json_path.parent.mkdir(parents=True, exist_ok=True)
        payload = {"steps": [asdict(s) | {"removed": s.removed} for s in self.steps], "facts": self.facts}
        json_path.write_text(json.dumps(payload, indent=2, default=str), encoding="utf-8")
        lines = [f"# {title}", "",
                 f"*Generated by `{command}`. Do not edit by hand.*", "",
                 "| Dataset | Step | Rows before | Rows after | Removed | Changed / flagged | Note |",
                 "|---|---|---:|---:|---:|---:|---|"]
        lines += [f"| {s.dataset} | {s.step} | {s.rows_before:,} | {s.rows_after:,} | {s.removed:,} | {s.affected:,} | {s.note} |"
                  for s in self.steps]
        lines += ["", "## Checks and facts", ""]
        for k, v in self.facts.items():
            if isinstance(v, (list, dict)) and len(json.dumps(v, default=str)) > 120:
                lines += [f"**{k}**", "", "```", json.dumps(v, indent=1, default=str), "```", ""]
            else:
                lines.append(f"- **{k}**: {v}")
        md_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
